const $ = id => document.getElementById(id);
const setting = name => document.querySelector(`meta[name="hcompany-${name}"]`)?.content.trim() ?? "";
const services = { fab: "fabTitle", elec: "elecTitle", tech: "techTitle" };
const booking = $("bookingModal");
let language = "en";
let selectedService = null;
let bookingOpener = null;

const copy = () => translations[language];
const serviceName = (service, locale = language) => translations[locale][services[service]];

function contactPhone(service) {
  const phone = setting(`${service}-phone`) || setting("phone");
  return /^\+?[0-9][0-9 ()-]{6,20}$/.test(phone) ? phone.replace(/[^\d+]/g, "") : "";
}

function paymentSettings(service) {
  const upi = setting(`${service}-upi`);
  const qr = setting(`${service}-qr`);
  // Treat the two ways to pay as a pair so they can't silently point to different recipients.
  return upi || qr ? { upi, qr } : { upi: setting("upi"), qr: setting("upi-qr") };
}

function updateEnquiry() {
  const service = $("enquiryService").value;
  const phone = contactPhone(service);
  const email = setting("email");
  const validEmail = /^[^\s@?&#%]+@[^\s@?&#%]+\.[^\s@?&#%]+$/.test(email);
  const number = $("enquiryNumber");
  const phoneLink = $("enquiryPhone");
  const emailLink = $("enquiryEmail");
  phoneLink.hidden = number.hidden = !phone;
  number.textContent = phone;
  if (phone) phoneLink.href = `tel:${phone}`;
  else phoneLink.removeAttribute("href");
  emailLink.hidden = !validEmail;
  if (validEmail) {
    const params = new URLSearchParams({
      subject: `H Company · ${copy().enquirySubject}: ${serviceName(service)}`,
      body: $("enquiryDetails").value.trim()
    });
    emailLink.href = `mailto:${encodeURIComponent(email).replace("%40", "@")}?${params.toString().replace(/\+/g, "%20")}`;
  } else emailLink.removeAttribute("href");
  $("enquiryUnavailable").hidden = Boolean(phone || validEmail);
}

function applyLanguage(value) {
  language = Object.hasOwn(translations, value) ? value : "en";
  document.documentElement.lang = language;
  $("languageSelect").value = language;
  for (const element of document.querySelectorAll("[data-t]")) {
    const key = element.dataset.t;
    if (Object.hasOwn(copy(), key)) element.textContent = copy()[key];
  }
  $("customerName").placeholder = copy().namePlaceholder;
  $("qrImage").alt = copy().qrAlt;
  $("closeModal").setAttribute("aria-label", copy().close);
  updateEnquiry();
  try { localStorage.setItem("hcompany-language", language); } catch {}
}

function getUpiId() {
  let { upi } = paymentSettings(selectedService);
  if (upi.toLowerCase().startsWith("upi://")) {
    try {
      const url = new URL(upi);
      if (url.protocol !== "upi:" || url.hostname !== "pay") return "";
      upi = url.searchParams.get("pa") || "";
    } catch { return ""; }
  }
  return /^[A-Za-z0-9._-]+@[A-Za-z0-9.-]+$/.test(upi) ? upi : "";
}

function getQrUrl() {
  const { qr } = paymentSettings(selectedService);
  if (!qr) return "";
  try {
    const url = new URL(qr, document.baseURI);
    return url.origin === location.origin && ["http:", "https:"].includes(url.protocol) ? url.href : "";
  } catch { return ""; }
}

function isMobileDevice() {
  return /Android|iPhone|iPad|iPod/i.test(navigator.userAgent) ||
    (navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1);
}

function setStatus(message = "") {
  $("status").textContent = message;
  $("status").hidden = !message;
}

function updatePayment() {
  const isQr = document.querySelector('input[name="paymentMethod"]:checked').value === "qr";
  const ready = Boolean(isQr ? getQrUrl() : getUpiId());
  const canPay = ready && $("agreement").checked;
  $("payButton").hidden = $("appFine").hidden = isQr;
  $("showQr").hidden = $("qrFine").hidden = !isQr;
  $("payButton").disabled = $("showQr").disabled = !canPay;
  if (!isQr || !canPay) $("qrPanel").hidden = true;
  setStatus(ready ? "" : copy()[isQr ? "qrUnavailable" : "configure"]);
}

function openBooking(button) {
  selectedService = button.dataset.service;
  bookingOpener = button;
  $("selectedName").textContent = serviceName(selectedService);
  $("agreement").checked = false;
  $("customerName").value = "";
  $("qrPanel").hidden = true;
  $("qrImage").removeAttribute("src");
  const useApp = isMobileDevice();
  document.querySelector(`input[name="paymentMethod"][value="${useApp ? "app" : "qr"}"]`).checked = true;
  updatePayment();
  booking.showModal();
  $("customerName").focus();
}

function bookingName() {
  const name = $("customerName").value.trim();
  if (name.length >= 2) return name;
  $("customerName").focus();
  setStatus(copy().enterName);
  return "";
}

