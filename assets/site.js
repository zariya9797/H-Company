function paymentUrl(upiId, name, service) {
  const note = (name + " - " + serviceName(service, "en")).slice(0, 80);
  const params = new URLSearchParams({pa: upiId, pn: "H Company", am: "149.00", cu: "INR", tn: note});
  return "upi://pay?" + params;
}

